    const glassRadius = panel.material.status.radius;
    panel.hide();
    if (desktopGlass) {
      assert.equal(panel.material.status.backend, 'desktop-blur', 'Glass must remain active while dismissal is prepared');
      await waitNative(() => panel.motion.phase === 'closing' || panel.motion.phase === 'closed');
      if (panel.motion.phase === 'closing') assert.equal(panel.material.status.radius, glassRadius, 'The closing slide must keep the settled blur');
    }
    await waitNative(() => panel.motion.phase === 'closed');
    assert.equal(panel.material.status.backend, 'none', 'Native blur is suspended while the panel is hidden');
    panel.show();
    await waitNative(() => panel.motion.phase === 'opening' || panel.motion.phase === 'open');
    if (desktopGlass) assert.equal(panel.material.status.radius, glassRadius, 'Glass must be active before the opening animation starts');
    await waitNative(() => panel.motion.phase === 'open');
    if (desktopGlass) assert.equal(panel.material.status.backend, 'desktop-blur');
    await click('Preferences'); await click('Themes');
    await click('Use Default theme');
    await waitFor(`document.documentElement.dataset.material === 'default'`);
    assert.equal(await run(`document.documentElement.style.getPropertyValue('--hue-teal')`), '');
    assert.equal(await run(`document.documentElement.style.getPropertyValue('--glass-pane-alpha')`), '');
    assert.ok(await run(`document.querySelector('.heading-glyph').getBoundingClientRect().width > 0`), 'Section icons remain visible in Default so chosen icons can be used in every theme');
    // Serve the same protocol as Onyx so light/dark changes and disconnections
