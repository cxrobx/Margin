  await dragStart('[data-folder-id="all"]');
  await dragTarget('[data-folder-id="personal"]', 'drop', 'after', 'x');
  await dragEnd();
  await waitFor(`document.querySelectorAll('.folder-tab')[3].dataset.folderId === 'all'`);
  assert.deepEqual(await tabIds(), ['work', 'inbox', 'personal', 'all']);
  assert.equal(await run(`document.querySelector('.folder-tab.selected').dataset.folderId`), 'all', 'Dragging tabs must keep the active folder');
  const savedRevision = (await store.read()).revision;
  await dragStart('[data-folder-id="inbox"]');
  await dragTarget('[data-folder-id="work"]', 'dragover', 'before', 'x');
  await dragEnd();
  await waitFor(`!document.querySelector('.is-dragging, .drop-before, .drop-after')`);
  assert.equal((await store.read()).revision, savedRevision, 'Canceling a drag must not save a move');
  await run(`document.querySelector('[data-folder-id="personal"]').dispatchEvent(new KeyboardEvent('keydown', { bubbles: true, altKey: true, key: 'ArrowLeft' }));`);
  await waitFor(`document.querySelectorAll('.folder-tab')[1].dataset.folderId === 'personal'`);
  await run(`document.querySelector('[data-note-id="${seedIds[0]}"]').dispatchEvent(new KeyboardEvent('keydown', { bubbles: true, altKey: true, key: 'ArrowUp' }));`);
