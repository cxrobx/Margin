    await waitFor(`document.documentElement.dataset.theme === 'dark'`);
    nativeTheme.themeSource = 'light';
    await waitFor(`document.documentElement.dataset.theme === 'light'`);
    nativeTheme.themeSource = 'system';
    await click('Light appearance');
    await waitFor(`document.documentElement.dataset.theme === 'light'`);
    await screenshot('margin-themes.png');
    await click('Use CXTasks Glass theme');
    await click('Dark appearance');
    await waitFor(`document.documentElement.dataset.material === 'glass' && document.documentElement.dataset.theme === 'dark'`);
    assert.notEqual(await run(`getComputedStyle(document.querySelector('[data-folder-id="all"] svg')).color`), await run(`getComputedStyle(document.documentElement).getPropertyValue('--muted').trim()`));
    assert.equal(await run(`getComputedStyle(document.querySelector('.heading-glyph')).display`), 'block');
    assert.equal(await run(`document.querySelectorAll('.folders .folder-dot').length`), 0, 'Folder tabs use the selectable icon instead of a color dot');
    const systemPrefs = await run(`window.margin.appearancePreferences()`);
    if (process.platform === 'darwin' && !systemPrefs.reducedTransparency) {
      assert.equal(panel.material.status.backend, 'desktop-blur', 'The bridge must apply the same desktop blur as CXTasks on this Mac');
      assert.ok(panel.material.status.radius > 0);
    }
    await screenshot('margin-glass-themes-dark.png');
    await click('Back to preferences'); await click('Back to notes');
    await screenshot('margin-glass-dark.png');
    await run(`Array.from(document.querySelectorAll('.folders > button')).find(el=>el.textContent==='Work').click()`);
    await waitFor(`document.querySelector('.section-heading h2').textContent === 'Work'`);
    assert.equal(await run(`getComputedStyle(document.querySelector('.heading-glyph')).color`), await run(`getComputedStyle(document.querySelector('[data-folder-id="work"] .folder-glyph')).color`), 'Folder and heading hues must match');
    await run(`Array.from(document.querySelectorAll('.folders > button')).find(el=>el.textContent==='All').click()`);
    await click('Preferences'); await click('Themes');
    await run(`const input = document.querySelector('[aria-label="Glass transparency"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'0.65'); input.dispatchEvent(new Event('input',{bubbles:true}));`);
    // Closing settings immediately after a drag must still save its last value.
    await click('Back to preferences');
    await waitNative(() => panel.material.status.radius === 35 || systemPrefs.reducedTransparency);
    assert.equal((await store.read()).settings.glassTransparency, .65);
    await click('Themes');
    await run(`window.margin.settings({glassTransparency:0})`);
    await waitFor(`document.documentElement.style.getPropertyValue('--glass-pane-alpha') === '1'`);
    assert.equal(panel.material.status.backend, 'none', 'Opaque means no native blur');
    await run(`window.margin.settings({glassTransparency:.38})`);
    const originalNativeTheme = panel.material.nativeTheme;
    panel.material.nativeTheme = { shouldUseDarkColors: true, prefersReducedTransparency: true };
    panel.material.render(true);
    win.webContents.send('appearance:preferences', { reducedTransparency: true });
    await waitFor(`document.querySelector('[aria-label="Glass transparency"]').disabled`);
    assert.equal(await run(`document.documentElement.style.getPropertyValue('--glass-sidebar-alpha')`), '1');
    assert.equal(panel.material.status.backend, 'none');
    assert.equal((await store.read()).settings.glassTransparency, .38);
    panel.material.nativeTheme = originalNativeTheme; panel.material.render(true);
    win.webContents.send('appearance:preferences', systemPrefs);
    await click('Light appearance');
    await waitFor(`document.documentElement.dataset.theme === 'light'`);
    await screenshot('margin-glass-themes-light.png');
    await click('Back to preferences'); await click('Back to notes');
    await screenshot('margin-glass-light.png');
