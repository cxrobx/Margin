  await screenshot('margin-note-drag.png');
  await dragTarget(`[data-note-id="${seedIds[0]}"]`, 'drop', 'before', 'y');
  await dragEnd();
  await waitFor(`document.querySelector('.note-card').dataset.noteId === '${seedIds[1]}'`);
  assert.equal((await store.list()).notes[0].id, seedIds[1]);
  assert.equal((await store.get(seedIds[1])).attachments.length, 0, 'Internal note drops must not attach files');
  await dragStart('[data-folder-id="work"]');
  await dragTarget('[data-folder-id="inbox"]', 'dragover', 'before', 'x');
  await waitFor(`document.querySelector('[data-folder-id="inbox"]').classList.contains('drop-before')`);
  await screenshot('margin-tab-drag.png');
  await dragTarget('[data-folder-id="inbox"]', 'drop', 'before', 'x');
  await dragEnd();
