  await waitFor(`document.querySelectorAll('.note-card').length === 6`);
  assert.equal(win.isVisible(), false, 'Startup must leave only the edge tab visible');
  if (process.platform === 'darwin') {
    assert.equal(app.dock.isVisible(), false, 'Utility must stay out of the Dock');
    assert.equal(win.isHiddenInMissionControl(), true);
  }
  assert.equal(win.isResizable(), false);
  assert.equal(win.isMinimizable(), false);
  assert.equal(win.isMaximizable(), false);
  assert.deepEqual(win.getBounds(), win.getContentBounds(), 'No native titlebar may reserve space');
  assert.equal(await run(`Boolean(document.querySelector('.window-bar'))`), false);
  assert.equal(panel.edgeBars.size, screen.getAllDisplays().length);
  const edgeBar = panel.edgeBars.values().next().value;
  if (edgeBar.webContents.isLoading()) await new Promise(resolve => edgeBar.webContents.once('did-finish-load', resolve));
  await waitNative(() => edgeBar.isVisible());
  assert.equal(edgeBar.isVisible(), true, 'The edge tab must be discoverable at startup');
  await edgeBar.webContents.executeJavaScript(`document.querySelector('button').click()`, true);
  await waitNative(() => win.isVisible());
  assert.equal(win.isVisible(), true, 'Clicking the edge tab opens the panel');
  assert.equal(edgeBar.isVisible(), false);
  const reducedMotion = await run(`matchMedia('(prefers-reduced-motion: reduce)').matches`);
  const translation = () => run(`new DOMMatrixReadOnly(getComputedStyle(document.getElementById('root')).transform).m41`);
  if (!reducedMotion) {
    await waitFor(`document.getElementById('root').getAnimations().length === 1`);
    const start = await translation();
    assert.ok(start > 0 && start < win.getBounds().width * 1.02, 'Right-edge opening starts to the right of its resting position');
    assert.equal(win.hasShadow(), false, 'Native shadow must not pop in ahead of the moving panel');
    await new Promise(r => setTimeout(r, 45));
    assert.ok(await translation() < start, 'The complete panel travels smoothly toward its resting position');
    await fs.writeFile(path.join(output, 'margin-slide-in.png'), (await win.webContents.capturePage()).toPNG());
  }
  await waitNative(() => panel.motion.phase === 'open');
  await waitFor(`document.getElementById('root').dataset.panelMotion === 'open'`);
  assert.equal(Math.round(await translation()), 0);
  assert.equal(win.hasShadow(), true);
  assert.equal(await run(`Boolean(window.margin)`), true);
  assert.equal(await run(`typeof window.require`), 'undefined');
  await screenshot('margin-notes.png');
  await iconsSmoke({ win, store, run, waitFor, click, screenshot });
  // Exercise the renderer's drag handlers, real IPC, and persistent notebook.
  const cardIds = () => run(`Array.from(document.querySelectorAll('.note-card')).map(el => el.dataset.noteId)`);
  const tabIds = () => run(`Array.from(document.querySelectorAll('.folder-tab')).map(el => el.dataset.folderId)`);
  const dragStart = selector => run(`
    window.smokeDragSource = document.querySelector(${JSON.stringify(selector)});
    window.smokeDragTransfer = new DataTransfer();
    window.smokeDragSource.dispatchEvent(new DragEvent('dragstart', { bubbles: true, cancelable: true, dataTransfer: window.smokeDragTransfer }));
  `);
  const dragTarget = (selector, event, placement, axis) => run(`
    const target = document.querySelector(${JSON.stringify(selector)}), bounds = target.getBoundingClientRect();
    target.dispatchEvent(new DragEvent(${JSON.stringify(event)}, { bubbles: true, cancelable: true, dataTransfer: window.smokeDragTransfer,
      clientX: bounds.left + bounds.width * ${axis === 'x' ? placement === 'before' ? .25 : .75 : .5},
      clientY: bounds.top + bounds.height * ${axis === 'y' ? placement === 'before' ? .25 : .75 : .5} }));
  `);
  const dragEnd = () => run(`window.smokeDragSource.dispatchEvent(new DragEvent('dragend', { bubbles: true, dataTransfer: window.smokeDragTransfer })); delete window.smokeDragSource; delete window.smokeDragTransfer;`);
