    assert.ok((await run(`document.querySelector('.config-box pre').textContent`)).includes(store.dir));
    await waitFor(`!document.querySelector('.toast')`);
    await screenshot('margin-connect.png');
    await click('Back to notes');
    await click('Preferences');
    await waitFor(`Boolean(document.querySelector('.preferences-content'))`);
    await click('Themes');
