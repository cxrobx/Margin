    const address = `http://127.0.0.1:${vaultServer.address().port}`;
    assert.equal((await run(`window.margin.settings({vaultAddress:${JSON.stringify(address)}})`)).ok, true);
    await run(`window.margin.vaultTheme(true)`);
    await waitFor(`!document.querySelector('[aria-label="Save vault theme copy"]').disabled`);
    await click('Match vault');
    await waitFor(`document.documentElement.style.getPropertyValue('--bg') === 'rgb(253 246 227)'`);
